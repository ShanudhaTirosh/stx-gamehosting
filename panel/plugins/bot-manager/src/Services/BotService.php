    /**
     * Add a package to NODE_PACKAGES / PY_PACKAGES or manifest file.
     */
    public static function installPackage(Server $server, string $packageName): bool
    {
        $runtime = static::getRuntime($server);
        $varName = ($runtime === 'node') ? 'NODE_PACKAGES' : 'PY_PACKAGES';

        $current = static::getVariableValue($server, $varName, '');
        $packages = array_filter(explode(' ', trim($current)));

        if (!in_array($packageName, $packages, true)) {
            $packages[] = $packageName;
            static::setVariableValue($server, $varName, implode(' ', $packages));
        }

        return true;
    }

    /**
     * Helper to get variable value from server variables.
     */
    protected static function getVariableValue(Server $server, string $envName, string $default = ''): string
    {
        $server->loadMissing('egg.variables');
        $eggVar = $server->egg?->variables?->firstWhere('env_variable', $envName);
        if (!$eggVar) {
            return $default;
        }

        $serverVar = ServerVariable::where('server_id', $server->id)
            ->where('variable_id', $eggVar->id)
            ->first();

        return $serverVar ? (string) $serverVar->variable_value : (string) ($eggVar->default_value ?? $default);
    }

    /**
     * Helper to set variable value on server.
     */
    protected static function setVariableValue(Server $server, string $envName, string $value): void
    {
        $server->loadMissing('egg.variables');
        $eggVar = $server->egg?->variables?->firstWhere('env_variable', $envName);
        if (!$eggVar) {
            return;
        }

        ServerVariable::updateOrCreate(
            ['server_id' => $server->id, 'variable_id' => $eggVar->id],
            ['variable_value' => $value]
        );
    }

    /**
     * Helper to read file from server container.
     */
    protected static function readFile(Server $server, string $path): string
    {
        /** @var DaemonFileRepository $repo */
        $repo = app(DaemonFileRepository::class)->setServer($server);

        return $repo->getContent($path);
    }

    /**
     * Helper to write file to server container.
     */
    protected static function writeFile(Server $server, string $path, string $content): void
    {
        /** @var DaemonFileRepository $repo */
        $repo = app(DaemonFileRepository::class)->setServer($server);

        $repo->putContent($path, $content);
    }
}

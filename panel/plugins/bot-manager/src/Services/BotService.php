    /**
     * Determine if a server is running a Bot or Generic Runtime (Node.js/Python).
     */
    public static function isBotServer(?Server $server): bool
    {
        if (!$server) {
            return false;
        }

        $server->loadMissing('egg');
        if (!$server->egg) {
            return false;
        }

        $name = strtolower($server->egg->name);
        $features = $server->egg->features ?? [];

        return str_contains($name, 'node')
            || str_contains($name, 'python')
            || str_contains($name, 'bot')
            || str_contains($name, 'discord')
            || str_contains($name, 'telegram')
            || in_array('bot', $features, true);
    }

    /**
     * Determine runtime type: 'node', 'python', or 'generic'.
     */
    public static function getRuntime(Server $server): string
    {
        $server->loadMissing('egg');
        $name = strtolower($server->egg?->name ?? '');

        if (str_contains($name, 'node') || str_contains($name, 'js')) {
            return 'node';
        }

        if (str_contains($name, 'python') || str_contains($name, 'py')) {
            return 'python';
        }

        return 'generic';
    }

    /**
     * Read and parse .env variables from server filesystem with cache fallback.
     */
    public static function getEnvVariables(Server $server): array
    {
        $cached = Cache::get("bot:env:{$server->id}");

        try {
            $content = static::readFile($server, '.env');
            if (!empty($content)) {
                $parsed = static::parseEnvContent($content);
                Cache::forever("bot:env:{$server->id}", $parsed);

                return $parsed;
            }
        } catch (Throwable $e) {
            Log::warning("Could not read .env for server {$server->id}: " . $e->getMessage());
        }

        return $cached ?? [];
    }

    /**
     * Save .env variables back to server filesystem and update cache.
     */
    public static function saveEnvVariables(Server $server, array $variables): bool
    {
        Cache::forever("bot:env:{$server->id}", $variables);

        $lines = ["# Generated by STX Bot Environment Manager"];
        foreach ($variables as $item) {
            $key = trim($item['key'] ?? '');
            $val = trim($item['value'] ?? '');
            if ($key !== '') {
                // If value contains spaces, wrap in quotes
                if (preg_match('/\s/', $val) && !str_starts_with($val, '"')) {
                    $val = '"' . addcslashes($val, '"') . '"';
                }
                $lines[] = "{$key}={$val}";
            }
        }

        $content = implode("\n", $lines) . "\n";

        try {
            static::writeFile($server, '.env', $content);

            return true;
        } catch (Throwable $e) {
            Log::warning("Daemon offline or failed writing .env for server {$server->id}: " . $e->getMessage());

            return true;
        }
    }

    /**
     * Parse raw .env file string into structured key/value array.
     */
    protected static function parseEnvContent(string $raw): array
    {
        $result = [];
        $lines = explode("\n", $raw);

        foreach ($lines as $line) {
            $line = trim($line);
            if (empty($line) || str_starts_with($line, '#')) {
                continue;
            }

            if (str_contains($line, '=')) {
                [$key, $val] = explode('=', $line, 2);
                $key = trim($key);
                $val = trim($val);
                // Strip outer quotes if present
                if ((str_starts_with($val, '"') && str_ends_with($val, '"')) ||
                    (str_starts_with($val, "'") && str_ends_with($val, "'"))) {
                    $val = substr($val, 1, -1);
                }

                $upperKey = strtoupper($key);
                $isSecret = str_contains($upperKey, 'TOKEN')
                    || str_contains($upperKey, 'SECRET')
                    || str_contains($upperKey, 'PASSWORD')
                    || str_contains($upperKey, 'KEY')
                    || str_contains($upperKey, 'AUTH')
                    || str_contains($upperKey, 'PASS');

                $result[] = [
                    'key' => $key,
                    'value' => $val,
                    'is_secret' => $isSecret,
                ];
            }
        }

        return $result;
    }

    /**
     * Retrieve Git repository and deployment configuration from egg variables.
     */
    public static function getGitStatus(Server $server): array
    {
        $server->loadMissing('variables');

        $gitAddress = static::getVariableValue($server, 'GIT_ADDRESS', '');
        $branch = static::getVariableValue($server, 'BRANCH', 'main');
        $autoUpdate = static::getVariableValue($server, 'AUTO_UPDATE', '0') === '1';
        $mainFile = static::getVariableValue($server, 'MAIN_FILE', static::getVariableValue($server, 'PY_FILE', 'index.js'));
        $userUpload = static::getVariableValue($server, 'USER_UPLOAD', '0') === '1';

        return [
            'git_address' => $gitAddress,
            'branch' => $branch ?: 'main',
            'auto_update' => $autoUpdate,
            'main_file' => $mainFile,
            'user_upload' => $userUpload,
        ];
    }

    /**
     * Update Git configuration variables for the server.
     */
    public static function saveGitSettings(Server $server, array $settings): bool
    {
        if (isset($settings['git_address'])) {
            static::setVariableValue($server, 'GIT_ADDRESS', $settings['git_address']);
        }
        if (isset($settings['branch'])) {
            static::setVariableValue($server, 'BRANCH', $settings['branch']);
        }
        if (isset($settings['auto_update'])) {
            static::setVariableValue($server, 'AUTO_UPDATE', $settings['auto_update'] ? '1' : '0');
        }
        if (isset($settings['main_file'])) {
            static::setVariableValue($server, 'MAIN_FILE', $settings['main_file']);
            static::setVariableValue($server, 'PY_FILE', $settings['main_file']);
        }

        return true;
    }

